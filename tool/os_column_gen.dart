bool _looksLikeType(String token) =>
    !_keywords.contains(token) &&
    RegExp(r'^[A-Za-z_][A-Za-z0-9_]*(?:<[^();={}]*>)?\??$').hasMatch(token);

/// Attempts to parse one statement as an eligible field declaration.
/// Returns null for methods, constructors, getters and anything unshaped.
ParsedField? tryParseField(String statement) {
  var work = statement.trim();
  while (work.endsWith(';')) {
    work = work.substring(0, work.length - 1).trimRight();
  }

  // Peel a leading @OsColumn(...) annotation off the front.
  ParsedFieldAnnotation? annotation;
  final annMatch = RegExp(r'^@OsColumn\b\s*\(').firstMatch(work);
  if (annMatch != null) {
    final open = annMatch.end - 1;
    final close = matchingParen(work, open);
    if (close == -1) return null;
    annotation = ParsedFieldAnnotation(
      parseAnnotationArgs(work.substring(open + 1, close)),
    );
    work = work.substring(close + 1).trim();
  }

  if (work.startsWith('@')) return null; // unsupported annotation carrier
  if (RegExp(r'[()]').hasMatch(work)) return null; // fn-ish: skip
  if (RegExp(r'\b(?:get|set)\b').hasMatch(work)) return null; // accessors

  // Drop any initializer (everything from the first top-level `=`).
  final eqIdx = work.indexOf('=');
  if (eqIdx != -1) work = work.substring(0, eqIdx).trim();

  final tokens = _splitTokens(work);
  if (tokens.isEmpty) return null;

  var idx = 0;
  var isFinal = false;
  var sawTypedDecl = false;
  while (idx < tokens.length) {
    final t = tokens[idx];
    if (t == 'static') {
      idx++;
    } else if (t == 'late') {
      idx++;
    } else if (t == 'final') {
      isFinal = true;
      sawTypedDecl = true;
      idx++;
    } else if (t == 'const') {
      return null; // const fields are compile-time data, not columns
    } else if (t == 'var') {
      sawTypedDecl = false;
      idx++;
      break;
    } else {
      break;
    }
  }
  final rest = tokens.sublist(idx);
  String name;
  if (!sawTypedDecl && rest.length == 1) {
    name = rest.single; // `var name`
  } else if (rest.length >= 2 && _looksLikeType(rest.first)) {
    name = rest.last; // `Type name`
  } else {
    return null;
  }

  if (!_isValidFieldName(name)) return null;
  final typeName = rest.length >= 2 ? rest.first : 'dynamic';
  return ParsedField(
    name: name,
    typeName: typeName.replaceAll(RegExp(r'\s+'), ''),
    isFinal: isFinal,
    annotation: annotation,
  );
}

/// Splits on whitespace outside of angle brackets / strings.
List<String> _splitTokens(String s) {
  final tokens = <String>[];
  var depth = 0;
  final buf = StringBuffer();
  for (var i = 0; i < s.length; i++) {
    final c = s[i];
    if (c == '<') depth++;
    if (c == '>') depth--;
    if (c == ' ' || c == '\t') {
      if (depth <= 0 && buf.isNotEmpty) {
        tokens.add(buf.toString());
        buf.clear();
        continue;
      }
      if (depth > 0) buf.write(c);
      continue;
    }
    buf.write(c);
  }
  if (buf.isNotEmpty) tokens.add(buf.toString());
  return tokens;
}

bool _isValidFieldName(String name) =>
    RegExp(r'^[a-z][A-Za-z0-9_]*$').hasMatch(name);

