/// Generates typed column-definition part files from annotated data classes.
///
/// Quality-program-v3 item 8 (codegen path). Scans `.dart` sources for
/// classes annotated with `@OsGridColumn()` and emits a sibling
/// `<file>.g.part` containing:
///
/// * a `<className camelCase>Columns({overrides})` function returning a
///   typed `List<OsColumnDef<T>>`, with real typed value getters
///   (`(p) => p.name`) — no stringly-typed field lookups;
/// * a `<ClassName>Cols` constants class of phantom-typed `ColumnRef`s
///   (item 38).
///
/// Usage:
/// ```
/// dart run tool/os_column_gen.dart [directory] [--check]
/// ```
///
/// The generator uses regex/brace scanning only — no mirrors, no
/// build_runner, no new package dependencies (zero-dep rule). It understands
/// plain field declarations (`final Type name;` / `Type name;`), optional
/// `@OsColumn(...)` annotations, and skips methods, constructors and
/// comments. Deliberately conservative: anything it cannot parse is skipped,
/// never guessed.
library;

import 'dart:io';

const String _generatedMarker =
    '// GENERATED CODE - DO NOT MODIFY BY HAND\n'
    '// Generated by tool/os_column_gen.dart (quality-program-v3 #8).\n';

const String _ignoreForFile = '// ignore_for_file: unused_import\n';

/// A parsed `@OsColumn(...)` annotation: raw argument key → literal text.
class ParsedFieldAnnotation {
  /// Builds an annotation record from raw literal arguments.
  const ParsedFieldAnnotation(this.args);

  /// Raw literal arguments, e.g. `{'headerName': "'Name'", 'width': '150'}`.
  final Map<String, String> args;

  /// Whether any metadata was supplied.
  bool get isEmpty => args.isEmpty;
}

/// A parsed class field eligible for column derivation.
class ParsedField {
  /// Builds a parsed field record.
  const ParsedField({
    required this.name,
    required this.typeName,
    required this.isFinal,
    this.annotation,
  });

  /// Declared Dart name of the field.
  final String name;

  /// Declared type as written (`String`, `int`, `List<int>`, …).
  final String typeName;

  /// Whether the declaration is `final` (immutable → no value setter).
  final bool isFinal;

  /// Attached `@OsColumn(...)`, when present.
  final ParsedFieldAnnotation? annotation;
}

/// A parsed `@OsGridColumn`-annotated class.
class ParsedClass {
  /// Builds a parsed class record.
  const ParsedClass({
    required this.name,
    required this.fields,
    this.configArgs = const {},
  });

  /// Class name.
  final String name;

  /// Ordered eligible fields (class-level `exclude` applies at emit time via
  /// the runtime factory).
  final List<ParsedField> fields;

  /// Raw class-level `@OsGridColumn(...)` literal arguments.
  final Map<String, String> configArgs;
}

/// Maps a declared type name to the schema kind used by the runtime factory.
String kindForType(String typeName) {
  const map = <String, String>{
    'String': 'text',
    'int': 'integer',
    'double': 'number',
    'num': 'number',
    'bool': 'boolean',
    'DateTime': 'date',
  };
  return map[typeName] ?? 'custom';
}

/// Lowercases the first character (`Person` → `person`).
String lowerFirst(String s) =>
    s.isEmpty ? s : '${s[0].toLowerCase()}${s.substring(1)}';

/// File name component of a POSIX- or Windows-style path.
String baseName(String path) {
  final normalized = path.replaceAll('\\', '/');
  final idx = normalized.lastIndexOf('/');
  return idx == -1 ? normalized : normalized.substring(idx + 1);
}

/// Strips line and block comments while preserving string literals well
/// enough for source scanning (adjacent-literal concatenation edge cases
/// aside).
String stripComments(String source) {
  return source.replaceAllMapped(
    RegExp(
      r"'(?:\\.|[^'\\])*'"
      r'|"(?:\\.|[^"\\])*"'
      r'|//[^\n]*'
      r'|/\*.*?\*/',
      dotAll: true,
    ),
    (m) => m.group(0)!.startsWith('/') ? '' : m.group(0)!,
  );
}

/// Index of the `)` closing the group opened at [openParen], honouring
/// nesting and string literals. -1 when unbalanced.
int matchingParen(String s, int openParen) {
  var depth = 0;
  var inString = false;
  for (var i = openParen; i < s.length; i++) {
    final c = s[i];
    if (inString) {
      if (c == r'\') i++;
      if (c == "'" || c == '"') inString = false;
      continue;
    }
    if (c == "'" || c == '"') {
      inString = true;
    } else if (c == '(') {
      depth++;
    } else if (c == ')') {
      depth--;
      if (depth == 0) return i;
    }
  }
  return -1;
}

/// Splits a top-level comma list into trimmed segments.
List<String> splitTopLevel(String s) {
  final parts = <String>[];
  var depth = 0;
  var inString = false;
  final buf = StringBuffer();
  for (var i = 0; i < s.length; i++) {
    final c = s[i];
    if (inString) {
      buf.write(c);
      if (c == r'\') {
        i++;
        if (i < s.length) buf.write(s[i]);
        continue;
      }
      if (c == "'" || c == '"') inString = false;
      continue;
    }
    if (c == "'" || c == '"') {
      inString = true;
      buf.write(c);
    } else if (c == '(' || c == '[' || c == '{') {
      depth++;
      buf.write(c);
    } else if (c == ')' || c == ']' || c == '}') {
      depth--;
      buf.write(c);
    } else if (c == ',' && depth == 0) {
      parts.add(buf.toString());
      buf.clear();
    } else {
      buf.write(c);
    }
  }
  final rest = buf.toString();
  if (rest.trim().isNotEmpty) parts.add(rest);
  return parts.map((p) => p.trim()).where((p) => p.isNotEmpty).toList();
}

/// Parses `key: value` pairs from an annotation argument body.
Map<String, String> parseAnnotationArgs(String body) {
  final result = <String, String>{};
  for (final part in splitTopLevel(body)) {
    final idx = part.indexOf(':');
    if (idx <= 0) continue;
    final key = part.substring(0, idx).trim();
    if (!RegExp(r'^[A-Za-z_][A-Za-z0-9_]*$').hasMatch(key)) continue;
    result[key] = part.substring(idx + 1).trim();
  }
  return result;
}

/// Extracts the balanced `{…}` body starting at [openBrace].
String extractBraceBody(String s, int openBrace) {
  var depth = 0;
  var inString = false;
  for (var i = openBrace; i < s.length; i++) {
    final c = s[i];
    if (inString) {
      if (c == r'\') i++;
      if (c == '"' || c == "'") inString = false;
      continue;
    }
    if (c == "'" || c == '"') {
      inString = true;
    } else if (c == '{') {
      depth++;
    } else if (c == '}') {
      depth--;
      if (depth == 0) return s.substring(openBrace + 1, i);
    }
  }
  return '';
}

final RegExp _annotationClassPattern = RegExp(
  r'@OsGridColumn\b\s*(?:\(([^()]*(?:\([^()]*\)[^()]*)*)\))?\s*'
  r'(?:abstract\s+)?(?:base\s+)?(?:interface\s+)?(?:final\s+)?(?:sealed\s+)?'
  r'(?:mixin\s+)?class\s+(\w+)',
);

/// Parses all `@OsGridColumn`-annotated classes out of [source], in
/// declaration order.
List<ParsedClass> parseAnnotatedClasses(String source) {
  final clean = stripComments(source);
  final classes = <ParsedClass>[];

  for (final match in _annotationClassPattern.allMatches(clean)) {
    final className = match.group(2)!;
    final braceIdx = clean.indexOf('{', match.end);
    if (braceIdx == -1 || clean.substring(match.end, braceIdx).contains(';')) {
      continue; // forward declaration or malformed — skip
    }
    final body = extractBraceBody(clean, braceIdx);

    final fields = <ParsedField>[];
    for (final decl in _topLevelStatements(body)) {
      final field = tryParseField(decl);
      if (field != null) fields.add(field);
    }

    final rawArgs = match.group(1);
    classes.add(
      ParsedClass(
        name: className,
        fields: fields,
        configArgs: rawArgs == null || rawArgs.trim().isEmpty
            ? const {}
            : parseAnnotationArgs(rawArgs),
      ),
    );
  }
  return classes;
}

/// Yields member-level chunks of a class [body].
///
/// A chunk ends at either a top-level `;` or — for members with block
/// bodies (methods, constructors, getters) — just before the body's `{`,
/// skipping the block entirely. Initialiser braces (`= {…}`, `: {…}`,
/// `=> {…}`) stay part of the chunk.
Iterable<String> _topLevelStatements(String body) sync* {
  var depth = 0;
  var start = 0;
  var inString = false;
  for (var i = 0; i < body.length; i++) {
    final c = body[i];
    if (inString) {
      if (c == r'\') i++;
      if (c == "'" || c == '"') inString = false;
      continue;
    }
    if (c == "'" || c == '"') {
      inString = true;
      continue;
    }
    final isBlockOpener =
        c == '{' && depth == 0 && !_isInitializerBrace(body, i);
    if (isBlockOpener) {
      // Member body: emit the declaration head, then skip the block.
      var end = i;
      while (end > start && _isSpace(body[end - 1])) {
        end--;
      }
      if (end > start) yield body.substring(start, end);
      i = _matchingBrace(body, i);
      start = i + 1;
      continue;
    }
    if (c == '(' || c == '[' || c == '{') {
      depth++;
    } else if (c == ')' || c == ']' || c == '}') {
      depth--;
    } else if (c == ';' && depth == 0) {
      yield body.substring(start, i);
      start = i + 1;
    }
  }
}

bool _isSpace(String c) => c == ' ' || c == '\t' || c == '\n' || c == '\r';

/// Whether the `{` at [idx] opens an initialiser expression rather than a
/// member body (`= {`, `: {`, `=> {`, `return {` style contexts).
bool _isInitializerBrace(String s, int idx) {
  var j = idx - 1;
  while (j >= 0 && _isSpace(s[j])) {
    j--;
  }
  if (j < 0) return false;
  final prev = s[j];
  if (prev == '=' || prev == ':' || prev == '(' || prev == ',') return true;
  if (prev == '>' && j >= 1 && s[j - 1] == '=') return true; // =>
  return false;
}

/// Index of the `}` matching the `{` at [openIdx] (string-aware), or
/// [openIdx] itself when unbalanced.
int _matchingBrace(String s, int openIdx) {
  var depth = 0;
  var inString = false;
  for (var i = openIdx; i < s.length; i++) {
    final c = s[i];
    if (inString) {
      if (c == r'\') i++;
      if (c == "'" || c == '"') inString = false;
      continue;
    }
    if (c == "'" || c == '"') {
      inString = true;
    } else if (c == '{') {
      depth++;
    } else if (c == '}') {
      depth--;
      if (depth == 0) return i;
    }
  }
  return openIdx;
}

