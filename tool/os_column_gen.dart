/// Renders one `OsColumnField<T>` list element for [field].
String emitFieldLiteral(String className, ParsedField field) {
  final ctor = 'OsColumnField<$className>.${kindForType(field.typeName)}';
  final args = <String>["'${field.name}'", '(p) => p.${field.name}'];
  if (!field.isFinal) {
    args.add('setValue: (p, v) => p.${field.name} = v as ${field.typeName}');
  }
  final meta = field.annotation;
  if (meta != null && !meta.isEmpty) {
    final rendered = _renderLiterals(meta.args, supportedMetaKeys);
    if (rendered.isNotEmpty) args.add('meta: OsColumn($rendered)');
  }

  final oneLine = '$ctor(${args.join(', ')})';
  if (oneLine.length <= 78 || args.length <= 2) return oneLine;
  final indented = args.map((a) => '        $a').join(',\n');
  return '$ctor(\n$indented,\n      )';
}

String _renderLiterals(Map<String, String> args, Set<String> keys) {
  final parts = <String>[];
  for (final entry in args.entries) {
    if (!keys.contains(entry.key)) continue;
    parts.add('${entry.key}: ${entry.value}');
  }
  return parts.join(', ');
}

String _emitConfigLiteral(Map<String, String> configArgs) {
  final rendered = _renderLiterals(configArgs, _supportedConfigKeys);
  if (rendered.isEmpty) return 'OsGridColumn()';
  return 'OsGridColumn($rendered)';
}

/// Emits the complete `.g.part` content for [classes].
///
/// [partOfName] is the owning library file name (e.g. `'person.dart'`).
String generatePartFile({
  required String partOfName,
  required List<ParsedClass> classes,
}) {
  final out = StringBuffer()
    ..write(_generatedMarker)
    ..writeln('// To regenerate, run:')
    ..writeln('//   dart run tool/os_column_gen.dart')
    ..writeln('// Owning library must import:')
    ..writeln("//   package:os_grid_flutter/os_grid_flutter.dart")
    ..writeln()
    ..write(_ignoreForFile)
    ..writeln("part of '$partOfName';")
    ..writeln();

  for (final cls in classes) {
    final fnName = '${lowerFirst(cls.name)}Columns';
    final colsName = '${cls.name}Cols';

    out
      ..writeln('/// Typed column definitions derived from [${cls.name}].')
      ..writeln('///')
      ..writeln(
        '/// Pass per-field [overrides] (keyed by field name) to supply',
      )
      ..writeln('/// behaviour annotations cannot express (custom renderers,')
      ..writeln('/// comparators, formatters). An override replaces the base')
      ..writeln(
        '/// definition but is back-filled with its accessor and identity.',
      )
      ..writeln('List<OsColumnDef<${cls.name}>> $fnName({')
      ..writeln('  Map<String, OsColumnDef<${cls.name}>> overrides = const {},')
      ..writeln('}) {')
      ..writeln('  return OsColumnDefs.fromSchema<${cls.name}>(')
      ..writeln('    OsColumnSchema<${cls.name}>(')
      ..writeln('      type: ${cls.name},')
      ..writeln('      config: ${_emitConfigLiteral(cls.configArgs)},')
      ..writeln('      fields: [');

    for (final field in cls.fields) {
      out.writeln('        ${emitFieldLiteral(cls.name, field)},');
    }

    out
      ..writeln('      ],')
      ..writeln('    ),')
      ..writeln('    overrides: overrides,')
      ..writeln('  );')
      ..writeln('}')
      ..writeln()
      ..writeln(
        '/// Phantom-typed column references for [${cls.name}] '
        '(quality-program-v3 #38).',
      )
      ..writeln('abstract final class $colsName {');

    for (final field in cls.fields) {
      out
        ..writeln('  /// Reference to the `${field.name}` column.')
        ..writeln(
          "  static const ${field.name} = "
          "ColumnRef<${cls.name}>.unchecked('${field.name}');",
        );
    }

    out
      ..writeln('}')
      ..writeln();
  }

  return out.toString();
}

/// Generates `.g.part` files for every annotated source under [directory].
///
/// Returns written paths. When [check] is true nothing is written and a
/// [GenerationCheckFailure] is thrown if any output would change.
List<String> generateInDirectory(Directory directory, {bool check = false}) {
  final touched = <String>[];
  final entities = directory.listSync(recursive: true)
    ..sort((a, b) => a.path.compareTo(b.path));

  for (final entity in entities) {
    if (entity is! File) continue;
    final name = baseName(entity.path);
    if (!name.endsWith('.dart')) continue;
    if (name.endsWith('.g.dart') || name.endsWith('.g.part')) continue;
    // Test fixtures often embed annotation samples in string literals.
    if (name.startsWith('_') || name.endsWith('_test.dart')) continue;

    final source = entity.readAsStringSync();
    if (!source.contains('@OsGridColumn')) continue;

    final classes = parseAnnotatedClasses(source);
    if (classes.isEmpty) continue;

    final output = generatePartFile(partOfName: name, classes: classes);
    final stem = name.substring(0, name.length - '.dart'.length);
    final outFile = File(
      '${entity.parent.path}${Platform.pathSeparator}$stem.g.part',
    );

    final exists = outFile.existsSync();
    if (!exists || outFile.readAsStringSync() != output) {
      if (check) throw GenerationCheckFailure(outFile.path);
      outFile.writeAsStringSync(output);
      touched.add(outFile.path);
    }
  }
  return touched;
}

/// Thrown by [generateInDirectory] in check mode when output drifts.
class GenerationCheckFailure implements Exception {
  /// Creates a failure for [path].
  GenerationCheckFailure(this.path);

  /// The stale file path.
  final String path;

  @override
  String toString() =>
      'Generated file out of date: $path\nRe-run '
      '`dart run tool/os_column_gen.dart`.';
}

void main(List<String> args) {
  var dir = '.';
  var check = false;
  for (final arg in args) {
    if (arg == '--check') {
      check = true;
    } else if (!arg.startsWith('-')) {
      dir = arg;
    } else {
      stderr.writeln('Unknown option: $arg');
      exitCode = 64;
      return;
    }
  }

  final directory = Directory(dir);
  if (!directory.existsSync()) {
    stderr.writeln('Directory not found: $dir');
    exitCode = 66;
    return;
  }

  try {
    final touched = generateInDirectory(directory, check: check);
    if (check) {
      stdout.writeln('os_column_gen --check OK');
    } else if (touched.isEmpty) {
      stdout.writeln('os_column_gen: nothing to generate.');
    } else {
      stdout.writeln('os_column_gen wrote ${touched.length} file(s):');
      for (final path in touched) {
        stdout.writeln('  $path');
      }
    }
  } on GenerationCheckFailure catch (e) {
    stderr.writeln(e.toString());
    exitCode = 65;
  }
}
